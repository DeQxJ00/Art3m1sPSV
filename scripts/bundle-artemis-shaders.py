"""Bundle the single PC-derived PSV effect set and exact-source aliases."""
from pathlib import Path
import json, struct, shutil, re, runpy

ROOT=Path(__file__).resolve().parents[1]

def tokens(text):
    text=re.sub(r'/\*.*?\*/|//[^\n]*','',text,flags=re.S)
    # A scalar zero initializes every vector component. Do not rewrite nonzero
    # literals or move alpha multiplications: those can change visible output.
    text=re.sub(r'\b(float[234])\s+(\w+)\s*=\s*0(?:\.0+)?\s*;',
        lambda m:f'{m[1]} {m[2]} = {m[1]}('+', '.join(['0.0']*int(m[1][-1]))+');',text)
    return tuple(re.findall(r'[A-Za-z_]\w*|(?:\d+\.?(?:\d*)?|\.\d+)(?:[eE][+-]?\d+)?[fF]?|==|!=|<=|>=|&&|\|\||\+\+|--|<<|>>|[^\s]',text))

def main():
    dst=ROOT/'shaders/psv'; core=ROOT/'core/src/backend/gxm'
    catalog=json.loads((dst/'catalog.json').read_text(encoding='utf-8'))
    entries=[]; unique={}; probe=[]; keys={}; contracts=[]
    byname={e['name']:e for e in catalog}
    def cg(e):return tokens((dst/e['cg']).read_text(encoding='utf-8'))
    for row in catalog:
        e=dict(row); p=dst/e['package']
        assert p.resolve().is_relative_to(dst.resolve())
        data=p.read_bytes(); assert data[:4]==b'AGX1'
        m,b=struct.unpack_from('<II',data,4);meta=json.loads(data[12:12+m]);gxp=data[12+m:]
        assert len(gxp)==b and gxp[:4]==b'GXP\0'
        assert meta['source_hash']==e['canonical_hash'] and meta['abi']==1
        e.update(bytes=b,uniforms=meta['uniforms']);entries.append(e)
        if e.get('contract'):
            target=e['contract'];candidates=[target]
            if target in {'blur_h','blur_v','cmul'}:candidates+=['glsl_mb_'+target,'glsl_sw_'+target]
            assert any(cg(e)==cg(byname[n]) for n in candidates if n in byname)
            contracts.append((e['name'],target))
        if e['package'] in unique:continue
        key=(cg(e),json.dumps(meta['uniforms'],sort_keys=True))
        assert key not in keys,('duplicate implementation',e['package'],keys.get(key))
        keys[key]=e['package'];unique[e['package']]=e
        n=e['implementation'];assert re.fullmatch('[A-Za-z_][A-Za-z0-9_]*',n)
        probe.append('static const unsigned char bundled_'+n+'[]={'+','.join(map(str,gxp))+'};')
        probe.append('static const BundledUniform uniforms_'+n+'[]={'+','.join('{"%s",%d,%d}'%(u['name'],u['offset'],u['count']) for u in meta['uniforms'])+'};')
    assert len({e['source_hash'] for e in entries})==len(entries)
    schema=runpy.run_path(str(ROOT/'scripts/shader-effect-schema.py'))
    descriptions=[schema['describe'](dst,e) for e in unique.values()]
    (dst/'parameters.json').write_text(json.dumps({'version':1,'effects':descriptions},indent=2)+'\n',encoding='utf-8')
    descriptions={e['implementation']:e for e in descriptions}
    (dst/'manifest.json').write_text(json.dumps(entries,indent=2)+'\n')
    module='// Generated by scripts/bundle-artemis-shaders.py.\npub(super) fn lookup(hash:&str)->Option<(&\'static str,&\'static str,&\'static [u8])>{Some(match hash {\n'
    for e in entries:module+='"%s"=>("%s","%s",include_bytes!("bundled/%s")),\n'%(e['source_hash'],e['name'],e['canonical_hash'],e['package'])
    module+='_=>return None,\n})}\n'
    equivalents=json.loads((dst/'equivalences.json').read_text(encoding='utf-8'))
    assert equivalents['version']==1
    module+='// Verified translated code AND parameter-layout equivalence; never filename inference.\npub(super) fn equivalent(hash:&str)->Option<(&\'static str,&\'static str,&\'static [u8])>{lookup(match hash {\n'
    seen=set()
    for alias in equivalents['matches']:
        name=alias['implementation'];fingerprint=alias['source_hash']
        assert re.fullmatch('[0-9a-f]{16}',fingerprint) and fingerprint not in seen
        seen.add(fingerprint)
        assert descriptions[name]['signature']==alias['signature'],('stale equivalence',fingerprint)
        target=next(e for e in entries if e['implementation']==name and e['source_hash']==e['canonical_hash'])
        module+='"%s"=>"%s",\n'%(fingerprint,target['source_hash'])
    module+='_=>return None,\n})}\n'
    module+='// Optimization contracts are distinct from approximate fallback selection.\npub(super) fn contract(name:&str)->&str{match name{\n'
    for name,target in sorted(set(contracts)):module+='"%s"=>"%s",\n'%(name,target)
    module+='_=>name,\n}}\n'
    # Explicit, reviewed same-function fallbacks. No suffix guessing or AA-to-blur substitution.
    fallback=json.loads((dst/'fallbacks.json').read_text())
    module+='pub(super) fn fallback(path:&str)->Option<(&\'static str,&\'static str,&\'static [u8])>{\nlet path=path.replace(\'\\\\\',"/").to_ascii_lowercase();\nlet relative=path.strip_prefix("system/shader/")?;\nlookup(match relative {\n'
    for path,name in sorted(fallback.items()):
        assert name in byname and '..' not in path.split('/')
        module+='"%s"=>"%s",\n'%(path,byname[name]['source_hash'])
    module+='_=>return None,\n})}\n'
    (dst/'bundled_effects.rs').write_text(module)
    output=core/'bundled';output.mkdir(exist_ok=True)
    for p in output.rglob('*.agxp'):
        assert p.resolve().is_relative_to(output.resolve())
        if p.relative_to(output).as_posix() not in unique:p.unlink()
    for name in unique:
        p=output/name;p.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(dst/name,p)
    shutil.copyfile(dst/'manifest.json',output/'manifest.json')
    shutil.copyfile(dst/'parameters.json',output/'parameters.json')
    shutil.copyfile(dst/'bundled_effects.rs',core/'bundled_effects.rs')
    probe.append('static const BundledEntry bundledEntries[]={')
    for e in unique.values():
        n=e['implementation'];probe.append('{"%s",bundled_%s,sizeof(bundled_%s),uniforms_%s,sizeof(uniforms_%s)/sizeof(BundledUniform)},'%(n,n,n,n,n))
    probe.append('};')
    (ROOT/'host-direct/src/bundled_probe_data.hpp').write_text('// Generated; diagnostic builds only.\n'+'\n'.join(probe)+'\n')
    print('Bundled',len(entries),'source aliases;',len(unique),'implementations;',sum(e['bytes'] for e in unique.values()),'GXP bytes')
if __name__=='__main__':main()
