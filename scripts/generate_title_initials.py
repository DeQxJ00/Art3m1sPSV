"""Regenerate the compact CJK initial table (requires pypinyin==0.55.0)."""
from pathlib import Path
from pypinyin import lazy_pinyin, Style

letters = []
for codepoint in range(0x3400, 0xA000):
    value = lazy_pinyin(chr(codepoint), style=Style.FIRST_LETTER, errors=lambda _: ["#"])[0].upper()
    letters.append(value if len(value) == 1 and "A" <= value <= "Z" else "#")
out = Path(__file__).resolve().parents[1] / "host-direct/src/title_initial_data.inc"
out.write_text("// Generated by scripts/generate_title_initials.py using pypinyin 0.55.0.\n"
               "// See third_party/licenses/pypinyin.txt for the MIT license.\n"
               + "\n".join('"' + "".join(letters[i:i+128]) + '"' for i in range(0, len(letters), 128)) + "\n", encoding="utf-8")
